#!/usr/bin/env python3
"""Regenerate references/document-catalog.md from template front matter.

  python3 scripts/build_catalog.py

Standard library only.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = ["formation", "founders", "equity-compensation", "employment-and-contractors",
         "commercial", "convertible-financing", "priced-financing", "governance", "compliance"]
HEADINGS = {
    "formation": "Formation",
    "founders": "Founder equity",
    "equity-compensation": "Equity compensation",
    "employment-and-contractors": "Employment and service providers",
    "commercial": "Commercial",
    "convertible-financing": "SAFEs and convertible notes",
    "priced-financing": "Priced equity rounds",
    "governance": "Governance",
    "compliance": "Compliance",
}


def field(front: str, key: str) -> str:
    m = re.search(rf"^{key}\s*:\s*(.+)$", front, re.M)
    return m.group(1).strip().strip("'\"") if m else ""


def main() -> None:
    lines = [
        "# Document Catalog",
        "",
        "Generated by `scripts/build_catalog.py` from each template's front matter. "
        "Checklists are in `checklists/`; reference guides in `references/`.",
        "",
    ]
    total = 0
    for folder in ORDER:
        files = sorted((ROOT / "templates" / folder).glob("*.md"))
        if not files:
            continue
        lines += [f"## {HEADINGS[folder]}", "", "| Template | Use when | Signers |", "|---|---|---|"]
        for path in files:
            text = path.read_text(encoding="utf-8")
            front = text[4:text.find("\n---", 4)] if text.startswith("---\n") else ""
            title = field(front, "title") or path.stem
            use = field(front, "use_when").replace("|", "/")
            signers = field(front, "signers").strip("[]").replace("|", "/")
            rel = path.relative_to(ROOT).as_posix()
            lines.append(f"| [{title}](../{rel}) | {use} | {signers} |")
            total += 1
        lines.append("")
    checklists = sorted((ROOT / "checklists").glob("*.md"))
    if checklists:
        lines += ["## Checklists", ""]
        for path in checklists:
            first = path.read_text(encoding="utf-8").splitlines()
            title = next((l.lstrip("# ").strip() for l in first if l.startswith("# ")), path.stem)
            lines.append(f"- [{title}](../{path.relative_to(ROOT).as_posix()})")
        lines.append("")
    out = ROOT / "references" / "document-catalog.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({total} templates, {len(checklists)} checklists)")


if __name__ == "__main__":
    main()
